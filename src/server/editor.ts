"use server";

import { Prisma } from "@prisma/client";

import { getI18n } from "@/i18n/server";
import { auth } from "@/lib/auth";
import { prisma } from "@/lib/prisma";
import { loadEditorCourse } from "@/lib/teach";
import {
  editorCourseSchema,
  type EditorCourse,
  type EditorCourseInput,
} from "@/lib/teach-editor";

/**
 * Persistence for the course editor (P5.1).
 *
 * The whole course is saved as one snapshot: settings, module and lesson order,
 * and every lesson's blocks. The editor holds the draft in the browser, so the
 * payload is re-validated here with `editorCourseSchema` — the same schema the
 * client runs before it calls this action. Nothing is written unless every
 * block of every lesson passes the block schema.
 *
 * Ids for new modules and lessons are generated by the client (UUID v4) and
 * inserted verbatim, which lets the editor keep working after a save without
 * waiting for a mapping. An id that is neither an existing row of this course
 * nor a fresh UUID is rejected instead of being written.
 */

export type SaveCourseResult =
  | { ok: true; course: EditorCourse }
  | { ok: false; error: string };

const FRESH_ID =
  /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/** The deepest first issue, phrased so it can be shown next to a field. */
function describeIssues(error: { issues: ReadonlyArray<{ path: PropertyKey[]; message: string }> }): string {
  const first = error.issues[0];
  if (first === undefined) {
    return "The course does not match the block schema.";
  }

  const path = first.path.map((segment) => String(segment)).join(".");
  return path.length === 0 ? first.message : `${path}: ${first.message}`;
}

export async function saveCourse(
  courseId: string,
  input: EditorCourseInput,
): Promise<SaveCourseResult> {
  const { t } = await getI18n();

  if (typeof courseId !== "string" || courseId.length === 0) {
    return { ok: false, error: t("server.editor.courseMissing") };
  }

  const session = await auth();
  const user = session?.user;
  if (user === undefined || (user.role !== "INSTRUCTOR" && user.role !== "ADMIN")) {
    return { ok: false, error: t("server.editor.signIn") };
  }

  const parsed = editorCourseSchema.safeParse(input);
  if (!parsed.success) {
    return {
      ok: false,
      error: `Nothing was saved. ${describeIssues(parsed.error)}`,
    };
  }

  const draft = parsed.data;

  const course = await prisma.course.findUnique({
    where: { id: courseId },
    select: {
      id: true,
      createdById: true,
      modules: { select: { id: true, lessons: { select: { id: true } } } },
    },
  });

  if (course === null) {
    return { ok: false, error: t("server.editor.courseGone") };
  }

  // Ownership is the edit guard: the middleware only proves the caller is a
  // teacher, not that this course is theirs.
  if (course.createdById !== user.id) {
    return { ok: false, error: t("server.editor.notOwner") };
  }

  const existingModuleIds = new Set(
    course.modules.map((courseModule) => courseModule.id),
  );
  const existingLessonIds = new Set(
    course.modules.flatMap((courseModule) =>
      courseModule.lessons.map((lesson) => lesson.id),
    ),
  );

  for (const courseModule of draft.modules) {
    if (!existingModuleIds.has(courseModule.id) && !FRESH_ID.test(courseModule.id)) {
      return {
        ok: false,
        error: t("server.editor.stale"),
      };
    }

    for (const lesson of courseModule.lessons) {
      if (!existingLessonIds.has(lesson.id) && !FRESH_ID.test(lesson.id)) {
        return {
          ok: false,
          error: t("server.editor.stale"),
        };
      }
    }
  }

  try {
    await prisma.$transaction(
      async (tx) => {
        await tx.course.update({
          where: { id: courseId },
          data: {
            title: draft.title,
            description: draft.description,
            audience: draft.audience,
            difficulty: draft.difficulty,
            coverEmoji: draft.coverEmoji,
            status: draft.status,
          },
        });

        // Rows dropped from the draft are deleted explicitly rather than by a
        // `notIn` on the whole course, so an incomplete payload can never wipe
        // a module the editor did not know about.
        const keptLessonIds = new Set(
          draft.modules.flatMap((courseModule) =>
            courseModule.lessons.map((lesson) => lesson.id),
          ),
        );
        const removedLessonIds = [...existingLessonIds].filter(
          (id) => !keptLessonIds.has(id),
        );
        if (removedLessonIds.length > 0) {
          await tx.lesson.deleteMany({ where: { id: { in: removedLessonIds } } });
        }

        const keptModuleIds = new Set(
          draft.modules.map((courseModule) => courseModule.id),
        );
        const removedModuleIds = [...existingModuleIds].filter(
          (id) => !keptModuleIds.has(id),
        );
        if (removedModuleIds.length > 0) {
          await tx.module.deleteMany({
            where: { courseId, id: { in: removedModuleIds } },
          });
        }

        for (const [moduleIndex, courseModule] of draft.modules.entries()) {
          if (existingModuleIds.has(courseModule.id)) {
            await tx.module.update({
              where: { id: courseModule.id },
              data: { title: courseModule.title, order: moduleIndex },
            });
          } else {
            await tx.module.create({
              data: {
                id: courseModule.id,
                courseId,
                title: courseModule.title,
                order: moduleIndex,
              },
            });
          }

          for (const [lessonIndex, lesson] of courseModule.lessons.entries()) {
            const lessonData = {
              title: lesson.title,
              order: lessonIndex,
              estimatedMinutes: lesson.estimatedMinutes,
              blocks: lesson.blocks as unknown as Prisma.InputJsonValue,
            };

            if (existingLessonIds.has(lesson.id)) {
              await tx.lesson.update({
                where: { id: lesson.id },
                data: { ...lessonData, moduleId: courseModule.id },
              });
            } else {
              await tx.lesson.create({
                data: {
                  id: lesson.id,
                  moduleId: courseModule.id,
                  ...lessonData,
                },
              });
            }
          }
        }
      },
      { timeout: 20_000 },
    );
  } catch (error: unknown) {
    console.error("[editor] failed to save the course", error);
    return {
      ok: false,
      error:
        "The course could not be saved. Your work is still on screen — check the connection and try again.",
    };
  }

  const saved = await loadEditorCourse(courseId);
  if (saved === null) {
    return {
      ok: false,
      error: t("server.editor.saveReloadFailed"),
    };
  }

  return { ok: true, course: saved };
}
